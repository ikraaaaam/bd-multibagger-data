export const DAMANI_SECTORS = new Set(["Pharma", "Engineering", "Consumer Staples", "Steel"]);

export function seededSpark(seed, base, trend = 0, len = 30) {
  let x = 0;
  for (let i = 0; i < seed.length; i++) x = (x * 31 + seed.charCodeAt(i)) % 100000;
  const points = [];
  
  // Backwards generate so that it ends roughly near `base` and follows the `trend`
  // This gives the impression that the price changed by `trend` over 30 days.
  let v = base * (1 - (trend / 100)); // Start point 30 days ago
  if (v <= 0) v = base * 0.9;
  
  for (let i = 0; i < len; i++) {
    x = (x * 1103515245 + 12345) % 2147483648;
    // Add noise + a slight bias towards the final `base` price
    const noise = ((x / 2147483648) - 0.5) * base * 0.03;
    const stepToTarget = (base - v) / (len - i);
    
    v = Math.max(base * 0.1, v + stepToTarget + noise);
    
    // Last point should match the base price exactly
    if (i === len - 1) {
      points.push(base);
    } else {
      points.push(v);
    }
  }
  return points;
}

export function healthScore(stock) {
  const profitability = Math.min(100, (stock.roe / 30) * 100);
  const balanceSheet = Math.min(100, Math.max(0, (1 - stock.de / 2) * 100));
  const earningsConsistency = stock.epsGrowth;
  const cashGeneration = stock.nocfps;
  const sectorBonus = DAMANI_SECTORS.has(stock.sector) ? 100 : 50;

  const score =
    profitability * 0.3 +
    balanceSheet * 0.25 +
    earningsConsistency * 0.2 +
    cashGeneration * 0.15 +
    sectorBonus * 0.1;

  return Math.round(score);
}

export function scoreColor(score) {
  if (score >= 75) return "#2fd888";
  if (score >= 60) return "#8fd42f";
  if (score >= 45) return "#c9a24b";
  if (score >= 30) return "#e08a3e";
  return "#e5555a";
}
